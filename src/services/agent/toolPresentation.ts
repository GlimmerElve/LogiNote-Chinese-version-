const PHASE_LABELS: Record<Exclude<AgentActivityPhase, 'tool'>, string> = {
  syncing: '正在同步最新学习数据',
  routing: '正在判断你的意图并选择合适的 Skill',
  memory: '正在读取本次需要的画像与记忆',
  coordinating: '正在组织专业 Agent 协同分析',
  reasoning: '正在分析信息并规划下一步',
  reviewing: '正在核对工具结果与证据',
  approval: '已准备好需要你确认的操作',
  stopping: '正在安全停止本次请求',
  finalizing: '正在整理最终回答',
};

export function agentToolLabel(toolName: string): string {
  return TOOL_LABELS[toolName] || '执行辅助操作';
}

export function agentActivityLabel(phase: AgentActivityPhase, toolName?: string): string {
  return phase === 'tool' ? `正在${agentToolLabel(toolName || '')}` : PHASE_LABELS[phase];
}
