- oppose：反对理由或反例→被削弱判断。仅比较词或转折词不构成反驳；不同条件下结果不同不自动矛盾。观察反对预期，不自动等于机制解释也被削弱。
- explain：说明材料→直接说明对象。可为来源/背景→情景、具体细节→概括、定义→概念使用处；任何类型均可参与，reason说明在解释什么，不要求“缺了就读不懂”才连线。
