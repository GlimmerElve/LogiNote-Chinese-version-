import assert from 'node:assert/strict';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { InteractiveFigureStore } from '../src/electron/interactiveFigureStore';

await mkdir('build', { recursive: true });
const root = await mkdtemp(path.resolve('build/figure-store-'));
const store = new InteractiveFigureStore(root), key = 'a'.repeat(64), other = 'b'.repeat(64);
assert.equal(await store.read(key), null);
await store.write(key, { status: 'pending' });
assert.deepEqual(await new InteractiveFigureStore(root).read(key), { status: 'pending' });
await store.write(key, { status: 'failed', error: '合成失败' });
assert.deepEqual(await store.read(key), { status: 'failed', error: '合成失败' });
await store.write(key, { status: 'ready', html: '<button>合成图</button>' });
assert.deepEqual(await new InteractiveFigureStore(root).read(key), { status: 'ready', html: '<button>合成图</button>' });
const design = { kind: 'quantitative' as const, anchor: '教材原句', goal: '理解关系', action: '调整输入', observation: '观察输出', model: '平方关系', prediction: '先预测', caveat: '示意', transfer: '换一个数' };
await store.write(key, { status: 'ready', html: '<button>合成图</button>', design });
assert.deepEqual(await new InteractiveFigureStore(root).read(key), { status: 'ready', html: '<button>合成图</button>', design });
const old = { status: 'ready' as const, html: '<button>合成图</button>', design };
const receipt={version:1 as const,status:'unresolved' as const,reason:'model-unavailable' as const,warnings:['prediction-consistency' as const],requested:true};
await store.write(key,{...old,repairReceipt:receipt});
assert.deepEqual((await new InteractiveFigureStore(root).read(key) as typeof old&{repairReceipt:typeof receipt}).repairReceipt,receipt);
assert.equal((await store.describe(key)).repairStatus,'unresolved');
const restoredKey='c'.repeat(64);
await store.write(restoredKey,{status:'failed',previousHtml:old.html,previousDesign:design,previousRepairReceipt:receipt});
assert.equal((await new InteractiveFigureStore(root).clearUnfinished(restoredKey)).restored,true);
assert.deepEqual((await store.read(restoredKey) as {repairReceipt:typeof receipt}).repairReceipt,receipt,'restoring a previous figure retains its check outcome');
const receiptPath=path.join(root,'interactive-figures',`${key}.json`),tamperedReceipt=JSON.parse(await readFile(receiptPath,'utf8'));
tamperedReceipt.repairReceipt.status='clean';await writeFile(receiptPath,JSON.stringify(tamperedReceipt));
await assert.rejects(store.read(key),/校验失败/u);
await store.write(key,old);
assert.equal(await store.compareReady(key, old, { ...old, html: '<button>修复图</button>', autoChecked: 1 }), true);
assert.deepEqual(await new InteractiveFigureStore(root).read(key), { ...old, html: '<button>修复图</button>', autoChecked: 1 });
assert.equal(await store.compareReady(key, old, { ...old, html: '<button>旧补丁</button>', autoChecked: 1 }), false, 'stale repairs cannot overwrite a newer figure');
await store.write(key, old);
const competing = await Promise.all([
  new InteractiveFigureStore(root).compareReady(key, old, { ...old, html: '<button>并发一</button>', autoChecked: 1 }),
  new InteractiveFigureStore(root).compareReady(key, old, { ...old, html: '<button>并发二</button>', autoChecked: 1 }),
]);
assert.equal(competing.filter(Boolean).length, 1, 'only one concurrent repair may replace the original');
await store.write(key, old);
const designLocation = path.join(root, 'interactive-figures', `${key}.json`);
const tamperedDesign = JSON.parse(await readFile(designLocation, 'utf8')); tamperedDesign.design.goal = '篡改';
await writeFile(designLocation, JSON.stringify(tamperedDesign));
await assert.rejects(store.read(key), /校验失败/u);
await store.write(key, { status: 'failed', error: '需要修复', draftHtml: '<p>草稿</p>', previousHtml: '<button>合成图</button>', previousDesign: design });
assert.deepEqual(await new InteractiveFigureStore(root).read(key), { status: 'failed', error: '需要修复', draftHtml: '<p>草稿</p>', previousHtml: '<button>合成图</button>', previousDesign: design });
await store.write(key, { status: 'failed', error: '重试失败', previousHtml: '<button>合成图</button>' });
assert.deepEqual(await new InteractiveFigureStore(root).read(key), { status: 'failed', error: '重试失败', previousHtml: '<button>合成图</button>' });
const largePrevious = `<button>${'"'.repeat(99_000)}</button>`;
const largeDraft = `<div>${'\\'.repeat(99_000)}</div>`;
await store.write(key, { status: 'failed', previousHtml: largePrevious, previousDesign: design, draftHtml: largeDraft });
assert.deepEqual(await new InteractiveFigureStore(root).read(key), { status: 'failed', previousHtml: largePrevious, previousDesign: design, draftHtml: largeDraft }, 'two valid escaped figures survive storage and restart');
await store.write(key, { status: 'ready', html: '<button>合成图</button>' });
assert.equal(await store.read(other), null, 'different page version cannot read the first attachment');
await assert.rejects(store.write('../unsafe', { status: 'ready', html: '<p>x</p>' }));
await assert.rejects(store.write(key, { status: 'ready', html: 'x'.repeat(100_001) }));
await assert.rejects(store.write(key, { status: 'ready', html: '\u0001'.repeat(10) }));
const location = path.join(root, 'interactive-figures', `${key}.json`);
const file = JSON.parse(await readFile(location, 'utf8')); file.html = '<p>changed</p>';
await writeFile(location, JSON.stringify(file));
await assert.rejects(store.read(key), /校验失败/u);
console.log('PASS figure attachment: restart, version keys, size/path checks and tamper detection');
