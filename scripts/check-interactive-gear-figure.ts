import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { buildInteractiveGearFigure, extractExternalGearFacts, wantsLocalGearFigure } from '../src/services/textbook/interactiveGearFigure';
import { interactiveFigureKey, prepareInteractiveFigure } from '../src/services/textbook/interactiveFigure';
import type { FigureArtifact } from '../src/electron/interactiveFigureStore';
import type { FigureDesign } from '../src/services/textbook/interactiveFigureDesign';

Object.defineProperty(globalThis, 'crypto', { value: webcrypto, configurable: true });
const lesson = '理想外啮合齿轮：主动齿轮有 12 齿，从动齿轮有 24 齿。忽略摩擦与滑动。';
const brief = '用简单线图观察齿轮传动的方向与转数。';
const facts = { driverTeeth: 12, drivenTeeth: 24 };
assert.deepEqual(extractExternalGearFacts(lesson), facts);
assert.equal(extractExternalGearFacts('主动齿轮12齿，从动齿轮24齿'), undefined, 'external meshing must be explicit');
assert.equal(extractExternalGearFacts(lesson + '另一个主动轮有 18 齿。'), undefined, 'conflicting counts must not be guessed');
assert.equal(extractExternalGearFacts(lesson + '还有一个内啮合齿轮。'), undefined);
assert.equal(extractExternalGearFacts('外啮合齿轮：主动轮6齿，从动轮301齿。'), undefined);
assert.deepEqual(wantsLocalGearFigure(brief, lesson, 'svg-2d'), facts);
assert.equal(wantsLocalGearFigure('讨论齿轮的三维结构', lesson, 'anatomy-3d'), undefined);
assert.equal(wantsLocalGearFigure('总结机械结构', lesson, 'svg-2d'), undefined);
assert.equal(wantsLocalGearFigure(brief, lesson, 'svg-2d', true), undefined);
const design: FigureDesign = { kind: 'quantitative', anchor: brief, goal: '观察转数', action: '改变转数', observation: '观察方向', model: '理想齿轮', prediction: '预测转数', caveat: '理想模型', transfer: '尝试其他齿数' };
const html = buildInteractiveGearFigure(facts, design);
assert.ok(html.includes('data-local-gear="true"') && html.includes('主动轮 12 齿') && html.includes('从动轮 24 齿'));
const circles = [...html.matchAll(/data-gear="(?:driver|driven)" cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"/gu)].map(m => ({ x: Number(m[1]), y: Number(m[2]), r: Number(m[3]) }));
assert.equal(circles.length, 2);
assert.ok(Math.abs(circles[1].x - circles[0].x - circles[0].r - circles[1].r) < 1e-5, 'pitch circles touch');
assert.equal(circles[1].r / circles[0].r, 2, 'radii follow tooth count');
assert.throws(() => buildInteractiveGearFigure({ driverTeeth: 0, drivenTeeth: 24 }, design));
assert.ok(!buildInteractiveGearFigure(facts, { ...design, goal: '</script><img src=x onerror=alert(1)>' }).includes('</script><img'));
const records = new Map<string, FigureArtifact>();
const api = { read: async (id: string) => records.get(id) || null, write: async (id: string, value: FigureArtifact) => { records.set(id, value); }, open: async () => ({ processId: 1 }), bounds: async () => {}, visible: async () => {}, close: async () => {}, onFailure: () => () => {} };
const key = await interactiveFigureKey('synthetic-gear', lesson, brief);
let calls = 0;
const built = await prepareInteractiveFigure(key, lesson, brief, false, { api, generate: async request => {
  calls++; assert.ok(request.systemPromptOverride?.includes('本地程序按材料中的主动轮'));
  assert.ok(request.systemPromptOverride?.includes('一次有效操作') && request.systemPromptOverride.includes('机械机制'));
  assert.deepEqual(JSON.parse(request.userInput).sourcedGearTeeth, facts);
  return { content: JSON.stringify({ design, html: '<script>MODEL_CODE_MUST_NOT_RUN</script>' }) };
} }, undefined, { before: lesson, after: '' });
assert.equal(calls, 1);
assert.ok(built.includes('data-local-gear="true"') && !built.includes('MODEL_CODE_MUST_NOT_RUN'));
const saved = records.get(key);
assert.equal(saved?.status, 'ready');
if (saved?.status === 'ready') assert.match(saved.design?.model || '', /主动轮12齿，从动轮24齿/u);
const deviceBrief = '观察齿轮装置的转向。';
const deviceKey = await interactiveFigureKey('synthetic-device', lesson, deviceBrief);
const device = await prepareInteractiveFigure(deviceKey, lesson, deviceBrief, false, { api, generate: async request => {
  assert.ok(request.systemPromptOverride?.includes('本地程序按材料中的主动轮'));
  return { content: JSON.stringify({ design: { ...design, anchor: deviceBrief } }) };
} }, undefined, { before: lesson, after: '' });
assert.ok(device.includes('data-local-gear="true"'), 'generic apparatus wording must not force a less reliable renderer');
console.log('PASS local gear: source-bound tooth counts, exact contact, deterministic ratio, safe model routing');
