import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { saveVaultNotesDelta, readSavedVaultNotesByIds } from '../src/electron/vaultNoteDelta';
import { materializeProgressiveKnowledge } from '../src/electron/progressiveKnowledge';
import { progressiveGoalContext } from '../src/services/progressiveLearning/materials';
import { progressiveExistingConcepts } from '../src/services/progressiveLearning/conceptPolicy';
import { progressiveGenerationRequest } from '../src/services/progressiveLearning/generation';
import { parseProgressiveResponse } from '../src/services/progressiveLearning/stream';
import { readProjectKnowledgeRows } from '../src/services/progressiveLearning/knowledgeProjection';
import type { NoteItem } from '../src/types';
import type { ProgressiveCourse } from '../src/services/progressiveLearning/types';

globalThis.fetch = async () => assert.fail('offline fixtures only');
const root = await fs.mkdtemp(path.resolve('build/progressive-core-concepts-'));
const vault = path.join(root, 'vault'), state = path.join(root, 'user-state');
const at = '2026-11-02T00:00:00Z';
const project: NoteItem = { id: 'leaf', title: '理解极限', noteType: 'project', content: 'PRIVATE_PROJECT_BODY', tags: [], links: [], backlinks: [], dueDates: [], createdAt: at, updatedAt: at };
const unrelated: NoteItem = { ...project, id: 'other', title: 'OUT_OF_SCOPE_TITLE', noteType: 'knowledge', parentId: 'other-project', content: 'PRIVATE_UNRELATED_BODY' };
await saveVaultNotesDelta(vault, state, { upserts: [project, unrelated].map(note => ({ note, before: null })), removed: [] });
const summary = '极限描述趋近过程：数列收敛表示其项趋近固定值；收敛数列的极限唯一。函数极限可讨论一点附近或无穷远处；一点处左右极限相同才存在整体极限。单调有界和夹逼是本页讨论的判定方法。';
const concept = { key: 'limit', title: '极限', summary };
const plan = { title: '理解极限', objectives: ['解释趋近及其判断'], pages: [{ id: 'main-1', title: '趋近', objectives: ['解释极限'] }, { id: 'main-2', title: '趋近的不同情形', objectives: ['判断条件'] }] };
const raw = `@@PLAN\n${JSON.stringify(plan)}\n@@LESSON\n# 极限\n\n${summary.repeat(2)}\n@@CONCEPTS\n${JSON.stringify([concept])}\n@@QUESTIONS\n${JSON.stringify([{ id: 'q1', kind: 'judgment', prompt: '左右极限不同时，整体极限存在，对吗？', objective: '核对条件', conceptKeys: ['limit'], focus: 'concept', options: [{ id: 'A', text: '不对' }, { id: 'B', text: '对' }], correctOptionId: 'A', referenceAnswer: '不对', explanation: '左右极限必须一致。' }])}\n@@HOOK\n${JSON.stringify({ id: 'hook', kind: 'reflection', prompt: '说明不同情形下的趋近。' })}\n@@END\n`;
const parsed = parseProgressiveResponse(raw);
assert.ok(parsed.complete);
assert.equal(parsed.concepts?.length, 1);
assert.deepEqual(parsed.questions![0].conceptKeys, ['limit']);
const firstIds = await materializeProgressiveKnowledge(vault, state, project.id, 'course', parsed.concepts!, () => true);
const secondIds = await materializeProgressiveKnowledge(vault, state, project.id, 'course', [{ ...concept, key: 'limit-next-page', summary: '继续讲解极限在一点处的条件。' }], () => true);
assert.deepEqual(firstIds, secondIds, 'another explanation/key for the same canonical noun reuses its note');
const [savedProject, core] = await readSavedVaultNotesByIds(vault, state, [project.id, firstIds[0]], { isCurrent: () => true });
assert.equal(core.title, '极限');
assert.ok(core.content.includes(summary), 'one core note retains all supplied facets');
assert.deepEqual(readProjectKnowledgeRows(savedProject.content).map(row => row.title), ['极限']);
const metadata = JSON.parse(await fs.readFile(path.join(vault, 'metadata.json'), 'utf8')).notesMeta;
assert.equal(Object.values(metadata).filter((note: any) => note.noteType === 'knowledge' && note.parentId === project.id).length, 1);
const scoped = progressiveGoalContext(savedProject, [savedProject, core, unrelated]);
assert.deepEqual(scoped.existingConcepts.map(row => row.title), ['极限']);
assert.ok(!JSON.stringify(scoped).includes('PRIVATE_') && !JSON.stringify(scoped).includes('OUT_OF_SCOPE'));
const course = { title: project.title, sourcePackets: [], pages: [], firstPage: { concepts: [concept] }, page: { concepts: [concept] }, plan,
  budget: { maxMainlinePages: 4, estimatedMinutes: 40 }, generation: { pageId: 'main-2', mainlineIndex: 1, sequence: 2 } } as unknown as ProgressiveCourse;
const payload = progressiveGenerationRequest(course, scoped), input = JSON.parse(payload.userInput);
assert.deepEqual(input.existingConcepts, [{ title: '极限', key: 'limit' }]);
assert.equal(input.conceptExtractionPolicy, 'core-concepts-v1');
assert.ok(!payload.userInput.includes('PRIVATE_') && !payload.userInput.includes(firstIds[0]));
assert.ok(payload.systemPromptOverride!.includes('同属一个对象就归到一个核心概念'));
assert.ok(!payload.systemPromptOverride!.includes('通常1–4项，最多8项'));
const before = JSON.stringify(course);
assert.equal(progressiveExistingConcepts(course, Array.from({ length: 100 }, (_, i) => ({ title: '概念' + i }))).length, 24);
assert.equal(JSON.stringify(course), before, 'reading the name catalogue does not mutate prior teaching');
const proof = { root, status: 'passed', coreNotes: 1, questionBinding: 'limit', repeatedPageReusesNote: true,
  nameOnlyContext: true, unchangedPublishedTeaching: true, network: 'blocked', quality: 'synthetic protocol/materialization fixtures; no live semantic evaluation' };
await fs.writeFile(path.join(root, 'result.json'), JSON.stringify(proof, null, 2));
console.log(JSON.stringify(proof));
