import assert from 'node:assert/strict';
import { ALIGNMENT_DATASET } from './cognition-alignment-dataset';
import { evaluateAlignment, type AlignmentOutcome } from './cognition-alignment-evaluation';
import type { CognitionAlignment } from '../src/services/cognition/alignment';

assert.equal(ALIGNMENT_DATASET.length, 24);
assert.equal(new Set(ALIGNMENT_DATASET.map((c) => c.id)).size, 24);
assert.equal(ALIGNMENT_DATASET.filter((c) => c.expected === 'clarify').length, 12);
assert.ok(ALIGNMENT_DATASET.every((c) => c.origin === 'synthetic' && c.personal && c.documents.length && c.reason));
const rows: AlignmentOutcome[] = ALIGNMENT_DATASET.map((c) => ({ id: c.id, method: 'local-hybrid-v1', targetRetrieved: true, targetSelected: true,
  decision: c.expected === 'clarify' ? { accepted: false, code: 'insufficient' } : { accepted: true, code: 'aligned', alignment: { relation: c.expected } as CognitionAlignment } }));
assert.equal(evaluateAlignment(ALIGNMENT_DATASET, rows).correct, 24);
assert.equal(evaluateAlignment(ALIGNMENT_DATASET, []).notCompleted, 24);
assert.equal(evaluateAlignment(ALIGNMENT_DATASET, []).correct, 0);
const changed = structuredClone(rows);
changed[0].decision = { accepted: false, code: 'unknown_metric' };
changed[1].decision.alignment!.relation = 'contradiction';
changed[2].targetSelected = false;
changed[3].targetRetrieved = false;
changed[4].error = 'transport_or_provider_failure';
changed[12].decision = { accepted: true, code: 'aligned', alignment: { relation: 'supplement' } as CognitionAlignment };
changed[13].targetRetrieved = false;
const scores = evaluateAlignment(ALIGNMENT_DATASET, changed);
assert.equal(scores.unnecessaryClarifications, 1);
assert.equal(scores.unsafeAcceptances, 1);
assert.equal(scores.wrongAcceptedRelationOrTarget, 3);
assert.equal(scores.correct, 17);
assert.equal(scores.notCompleted, 1);
assert.equal(scores.targetRetrieved, 22);
assert.equal(scores.productionApproved, false);
const malformed = structuredClone(rows);
malformed[12].decision = { accepted: false, code: 'invalid_format' };
const protocolScores = evaluateAlignment(ALIGNMENT_DATASET, malformed);
assert.equal(protocolScores.correct, 23);
assert.equal(protocolScores.protocolFailures, 1);
assert.equal(protocolScores.safeRejectionsOfClarifyCases, 12);
assert.equal(protocolScores.unsafeAcceptances, 0);
const wordingOnly = structuredClone(rows);
wordingOnly[0].decision = { accepted: false, code: 'certainty_only', certaintyNotice: { personalQuote: '必定', documentQuote: '不保证', sourceId: 'D1' } };
const wordingScores = evaluateAlignment(ALIGNMENT_DATASET, wordingOnly);
assert.equal(wordingScores.correct, 23); // A useful wording observation is not a fully aligned relation.
assert.equal(wordingScores.limitedCertaintyNotices, 1);
assert.equal(wordingScores.unnecessaryClarifications, 0);
const missingBasis = structuredClone(rows);
missingBasis[0].decision = { accepted: false, code: 'missing_relation_basis' };
assert.equal(evaluateAlignment(ALIGNMENT_DATASET, missingBasis).protocolFailures, 1);
assert.throws(() => evaluateAlignment(ALIGNMENT_DATASET, [...rows, rows[0]]));
assert.throws(() => evaluateAlignment(ALIGNMENT_DATASET, [{ ...rows[0], id: 'unknown' }]));
console.log('PASS alignment evaluation: fixed scope, full denominators, retrieval misses, unsafe acceptance, over-abstention, relation/target errors, transport failure, ID validation');
